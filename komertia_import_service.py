"""Add-only importer for existing neondb/public.allegro_state, with atomic audit."""
from datetime import datetime, timezone
from decimal import Decimal
import copy
import json
import uuid
import storage

LOCK_ID = 190102026
LOG_KEY = 'komertia_import_log'


class ImportErrorSafe(ValueError):
    pass


def decode(value):
    return json.loads(value) if isinstance(value, str) else value


def plan_import(existing, quote):
    by_id = {r.get('_position_id'): r for r in existing}
    by_source = {(r.get('source_order_id'), r.get('source_product_id')): r for r in existing if r.get('source_order_id') and r.get('source_product_id')}
    additions, states, archived = [], [], 0
    for row in quote.records:
        old = by_id.get(row['_position_id']) or by_source.get((quote.order_id, row['source_product_id']))
        if old is None:
            additions.append(copy.deepcopy(row))
            states.append('Новая')
        else:
            if Decimal(str(old.get('Ilość', 0))) != Decimal(str(row['Ilość'])) or Decimal(str(old.get('Закупка PLN', 0))) != Decimal(str(row['Закупка PLN'])):
                raise ImportErrorSafe('Выцена отличается от уже сохранённого товара по количеству или себестоимости. Существующие данные не изменены.')
            is_archived = old.get('_archived_no_allegro_price') is True or old.get('_archived_duplicate') is True
            archived += int(is_archived)
            states.append('Архив — сохранён' if is_archived else 'Уже есть — без изменений')
    return additions, states, archived


def snapshot():
    """Preview must not call the legacy loader that migrates names/archives."""
    if not storage.is_external():
        raise ImportErrorSafe('Neon не подключён: настройте ALLEGRO_DATABASE_URL в Streamlit Secrets.')
    try:
        db = storage.state_connection(ensure_table=False)
    except Exception:
        raise ImportErrorSafe('Neon недоступен. Проверьте подключение в Secrets; данные не изменены.') from None
    try:
        with db:
            if db.execute('SELECT current_database()').fetchone()[0] != 'neondb':
                raise ImportErrorSafe('Выбрана другая база. Импорт разрешён только в neondb.')
            rows = db.execute("SELECT key,value FROM public.allegro_state WHERE key IN ('analysis','prices',%s)", (LOG_KEY,)).fetchall()
            state = {key: decode(value) for key, value in rows}
            if not isinstance(state.get('analysis'), list) or not isinstance(state.get('prices'), dict):
                raise ImportErrorSafe('Не найдены существующие analysis/prices в public.allegro_state.')
            return state['analysis'], state.get(LOG_KEY, [])
    except ImportErrorSafe:
        raise
    except Exception:
        raise ImportErrorSafe('Не удалось прочитать Neon. Проверьте подключение и права; реквизиты в сообщении не выводятся.') from None
    finally:
        db.close()


def _write(db, key, value):
    # Supports both text and jsonb value columns, like the reviewed SQL scripts.
    db.execute('''INSERT INTO public.allegro_state(key,value)
        SELECT %s,(jsonb_populate_record(NULL::public.allegro_state,jsonb_build_object('value',%s::jsonb))).value
        ON CONFLICT(key) DO UPDATE SET value=excluded.value''', (key, json.dumps(value, ensure_ascii=False, allow_nan=False)))


def _read(db, key):
    row = db.execute('SELECT value FROM public.allegro_state WHERE key=%s', (key,)).fetchone()
    return decode(row[0]) if row else None


def _log_failure(quote):
    """Audit a failed confirmed attempt separately, after its data transaction rolled back."""
    db = None
    try:
        db = storage.state_connection(ensure_table=False)
        with db:
            db.execute('SELECT pg_advisory_xact_lock(%s)', (LOCK_ID,))
            log = _read(db, LOG_KEY) or []
            if isinstance(log, list):
                _write(db, LOG_KEY, log + [{'operation_id': str(uuid.uuid4()),
                    'time': datetime.now(timezone.utc).isoformat(), 'order_id': quote.order_id,
                    'batch': quote.batch, 'digest': quote.digest, 'status': 'failed',
                    'added': 0, 'error_code': 'IMPORT_ROLLED_BACK'}])
    except Exception:
        # A connection outage can also prevent audit persistence; never hide the original failure.
        pass
    finally:
        if db is not None:
            db.close()


def confirm_import(quote, acknowledged=False):
    if not acknowledged:
        raise ImportErrorSafe('Нужно подтвердить проверку предпросмотра и расхождений.')
    # No local SQLite fallback. Parser result is regenerated by the UI at confirmation.
    if not storage.is_external():
        raise ImportErrorSafe('Neon недоступен. Импорт в локальную SQLite запрещён.')
    try:
        db = storage.state_connection(ensure_table=False)
    except Exception:
        raise ImportErrorSafe('Neon недоступен. Проверьте подключение в Secrets; данные не изменены.') from None
    can_log = False
    try:
        with db:
            if db.execute('SELECT current_database()').fetchone()[0] != 'neondb':
                raise ImportErrorSafe('Импорт разрешён только в существующую neondb.')
            db.execute("SET LOCAL lock_timeout='10s'")
            db.execute("SET LOCAL statement_timeout='60s'")
            db.execute('SELECT pg_advisory_xact_lock(%s)', (LOCK_ID,))
            db.execute("SELECT key FROM public.allegro_state WHERE key IN ('analysis','prices') ORDER BY key FOR UPDATE")
            before = _read(db, 'analysis')
            prices = _read(db, 'prices')
            if not isinstance(before, list) or not isinstance(prices, dict):
                raise ImportErrorSafe('Ожидались существующие analysis/prices, импорт отменён.')
            can_log = True
            log = _read(db, LOG_KEY) or []
            if not isinstance(log, list):
                raise ImportErrorSafe('Неверный формат журнала импортов.')
            additions, states, archived = plan_import(before, quote)
            previous = [entry for entry in log if entry.get('order_id') == quote.order_id and entry.get('status') == 'imported']
            if previous and any(entry['digest'] != quote.digest for entry in previous):
                raise ImportErrorSafe('Эта выцена уже импортирована с другим содержимым. Автоматическая перезапись запрещена.')
            new_prices = copy.deepcopy(prices)
            for row in additions:
                old_price = prices.get(row['_position_id'])
                if isinstance(old_price, dict):
                    row.update({c: old_price[c] for c in storage.SALES if c in old_price})
                else:
                    new_prices[row['_position_id']] = {c: row[c] for c in storage.SALES}
            combined = before + additions
            batch_rows = [r for r in combined if r.get('source_order_id') == quote.order_id]
            if (len(batch_rows) != len(quote.records)
                or sum(Decimal(str(r['Ilość'])) for r in batch_rows) != Decimal(str(quote.report['quantity']))
                or sum(Decimal(str(r['Ilość'])) * Decimal(str(r['Закупка PLN'])) for r in batch_rows) != Decimal(quote.report['unit_price_total'])):
                raise ImportErrorSafe('Контрольные суммы сохранённой партии отличаются от предпросмотра; запись отменена.')
            event = {'operation_id': str(uuid.uuid4()), 'time': datetime.now(timezone.utc).isoformat(),
                     'order_id': quote.order_id, 'batch': quote.batch, 'digest': quote.digest,
                     'status': 'imported' if additions else 'already_imported', 'added': len(additions),
                     'skipped': len(states)-len(additions), 'archived_untouched': archived, 'report': quote.report}
            if additions:
                _write(db, 'analysis', combined)
                _write(db, 'prices', new_prices)
            _write(db, LOG_KEY, log + [event])
            if _read(db, 'analysis') != combined or _read(db, 'prices') != new_prices or _read(db, LOG_KEY) != log + [event]:
                raise ImportErrorSafe('Проверка записи не пройдена. Транзакция отменена.')
            # Additional checks protect old records, including arbitrary metadata/photos.
            if combined[:len(before)] != before or any(new_prices.get(k) != v for k, v in prices.items()):
                raise ImportErrorSafe('Проверка сохранности старых данных не пройдена.')
        return combined, event
    except ImportErrorSafe:
        if can_log:
            _log_failure(quote)
        raise
    except Exception:
        if can_log:
            _log_failure(quote)
        raise ImportErrorSafe('Импорт не завершён. Транзакция отменена; проверьте доступность Neon. Реквизиты скрыты.') from None
    finally:
        db.close()
